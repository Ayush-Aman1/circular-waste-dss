"""Closed-loop daily simulation. All bin-level data is SYNTHETIC (every record carries synthetic=True).

Day d (after `warmup_days` of baseline 2-day-emptying history from the virtual-bin generator):
  1. forecast today's generation per point from history up to d-1 (LightGBM) -> P(overflow if not visited), recalibrated
  2. recovery value of each bin's current content at the forecast composition (14-day mean shares x segregation x efficiency x price)
  3. policy -> prize per point (INR); router (OR-Tools or PyVRP) picks which bins to visit with the trip slots of the fleet
  4. collect: visited bins are emptied; their mass by material goes to the flow model (facility capacities, recovery, landfill)
  5. bins receive today's generation (identical for every policy on the same seed); mass above capacity overflows (tracked, never lost silently)
Mass balance each day: stock_start + generated = stock_end + collected + overflow (tested). Warm-up history is shared by all policies, so
policy comparisons are paired by seed.
"""
from __future__ import annotations

import time
from dataclasses import dataclass, field

import numpy as np
import pandas as pd

from circwaste import route as router
from circwaste.config import val
from circwaste.flow import FlowModel
from circwaste.forecast.live import LiveForecaster
from circwaste.geo.world import Study
from circwaste.metrics.summary import summarise
from circwaste.models import MATERIALS, DayState, Vehicle
from circwaste.priority import DayForecast, make_policy
from circwaste.sim.generator import build_world, generate_history
from circwaste.scenario.levers import Levers, apply_levers

MAT_COLS = [f"kg_{m}" for m in MATERIALS]


@dataclass
class Exogenous:
    """Policy-independent part of a synthetic world for one seed: generation and composition of every day, plus the baseline warm-up fill."""
    seed: int
    gen: np.ndarray             # (T, n) kg generated
    mat: np.ndarray             # (T, n, 8) kg generated by material
    weekday: np.ndarray         # (T,)
    festival: np.ndarray        # (T,)
    base_fill_end: np.ndarray   # (T, n) baseline-schedule fill at the end of each day (only warm-up days are used)
    cap: np.ndarray             # (n,)
    point_ids: list[str]
    wards: np.ndarray


def make_exogenous(study: Study, cfg: dict, seed: int, total_days: int) -> Exogenous:
    world = build_world(study.points, cfg)
    h = generate_history(world, seed, days=total_days)
    n = len(world.points)
    h = h.sort_values(["day", "point_id"]).reset_index(drop=True)
    order = sorted(world.points.point_id)
    assert h.point_id.iloc[:n].tolist() == order
    pts = world.points.set_index("point_id").loc[order]
    g = lambda c: h[c].to_numpy().reshape(total_days, n)   # noqa: E731
    return Exogenous(seed, g("generated_kg"), np.stack([g(c) for c in MAT_COLS], axis=2), h.weekday.to_numpy().reshape(total_days, n)[:, 0],
                     h.festival.to_numpy().reshape(total_days, n)[:, 0], g("fill_end_kg"), pts.capacity_kg.to_numpy(), order, pts.ward.to_numpy())


@dataclass
class RunResult:
    policy: str
    seed: int
    days: pd.DataFrame
    summary: dict
    detail: list[dict] = field(default_factory=list)     # per-day routes / bin states (keep_detail=True)
    runtime_s: float = 0.0


def _vehicles(cfg: dict, lv: Levers) -> list[Vehicle]:
    v = val(cfg, "costs.vehicle")
    trips = int(val(cfg, "fleet.trips_per_vehicle_per_day"))
    count = max(int(v["count"]) - int(lv.vehicles_unavailable), 0)
    return [Vehicle(id=f"v{k}_t{j}", capacity_kg=float(v["capacity_kg"]), cost_per_km=float(v["cost_per_km"])) for k in range(count) for j in range(trips)]


def _window(ex: Exogenous, fill_end: np.ndarray, d0: int, d1: int) -> pd.DataFrame:
    """History rows for days [d0, d1) in the layout the feature builder expects."""
    n = len(ex.point_ids)
    days = np.arange(d0, d1)
    return pd.DataFrame({
        "sim_seed": ex.seed, "point_id": np.tile(ex.point_ids, len(days)), "ward": np.tile(ex.wards, len(days)), "day": np.repeat(days, n),
        "weekday": np.repeat(ex.weekday[days], n), "festival": np.repeat(ex.festival[days], n),
        "generated_kg": ex.gen[days].ravel(), "fill_end_kg": fill_end[days].ravel(), "capacity_kg": np.tile(ex.cap, len(days)),
        "kg_organic": ex.mat[days][:, :, 0].ravel()})


def run_loop(policy_name: str, seed: int, study: Study, cfg: dict, lcfg: dict, pcfg: dict, fc: LiveForecaster, levers: Levers | None = None,
             exo: Exogenous | None = None, keep_detail: bool = False, eval_days: int | None = None) -> RunResult:
    t_start = time.time()
    lv = levers or Levers(policy=policy_name)
    cfg = apply_levers(cfg, lv)
    warm = int(lcfg["warmup_days"])
    n_eval = int(eval_days or lcfg["eval_days"])
    total = warm + n_eval
    if exo is None:
        exo = make_exogenous(study, cfg, seed, total)
    n = len(exo.point_ids)
    pos = {p: i for i, p in enumerate(exo.point_ids)}
    # matrix rows follow study.points order; map to the sorted point order used by the arrays
    idx = np.array([study.points.index[study.points.point_id == p][0] for p in exo.point_ids])
    sel = np.concatenate([[0], idx + 1])
    dist_m, time_s = study.dist_m[np.ix_(sel, sel)], study.time_s[np.ix_(sel, sel)]

    seg = float(val(cfg, "segregation.rate"))
    eff = np.array([val(cfg, "recovery.efficiency")[m] for m in MATERIALS])
    price = np.array([val(cfg, "recovery.price_per_kg")[m] for m in MATERIALS])
    unit_value = seg * eff * price                                    # INR per kg of each material that reaches recovery
    oc = float(val(cfg, "costs.overflow_cost_inr"))
    veh_cfg = val(cfg, "costs.vehicle")
    cpk, fixed_daily = float(veh_cfg["cost_per_km"]), float(veh_cfg["fixed_daily"])
    service_h = float(val(cfg, "fleet.service_minutes_per_stop")) / 60.0
    vehicles = _vehicles(cfg, lv)

    fac = study.facilities
    dest = fac[fac.kind.isin(["wet_plant", "biomethanation"])].sort_values("dist_km")
    dest = dest if len(dest) else fac[fac.kind != "landfill"].sort_values("dist_km")
    leg_km, leg_s = float(dest.dist_km.iloc[0]), float(dest.time_s.iloc[0])      # depot -> unloading facility (one way)
    trip_fixed = 2.0 * leg_km * cpk                                  # every trip ends with a facility round trip from the depot
    flow = FlowModel(fac, cfg, segregation=seg, capacity_pct=lv.capacity_pct)

    pol = make_policy(policy_name, pcfg, cfg, lv.alpha, lv.beta)
    backend = pcfg["policies"][policy_name].get("router", "ortools")
    rkw = dict(lcfg["router"][backend])

    # ---- initial state at the end of warm-up (baseline schedule)
    fill_end = exo.base_fill_end.copy()
    w0 = max(warm - 14, 0)
    sh = exo.mat[w0:warm].sum(0)
    sh = sh / np.maximum(sh.sum(1, keepdims=True), 1e-9)
    fill_mat = fill_end[warm - 1][:, None] * sh
    stock = {p: 0.0 for p in exo.point_ids}
    rows, detail = [], []
    W = int(lcfg["forecast_window_days"])

    for d in range(warm, total):
        fill = fill_mat.sum(1)
        feat = fc.features(_window(exo, fill_end, d - W, d), d, int(exo.weekday[d]), int(exo.festival[d])).set_index("point_id").loc[exo.point_ids].reset_index()
        gen_pred, risk = fc.predict(feat, fill, exo.cap, lv.forecast_noise, exo.gen[d])
        recent = exo.mat[d - 14:d].sum(0)
        shares = recent / np.maximum(recent.sum(1, keepdims=True), 1e-9)
        value = fill * (shares * unit_value).sum(1)
        fcast = DayForecast(exo.point_ids, fill, exo.cap, gen_pred, risk, value)
        state = DayState(day=d, fill_kg={p: dict(zip(MATERIALS, fill_mat[i])) for i, p in enumerate(exo.point_ids)} if keep_detail else {},
                         facility_stock_kg=dict(flow.stock))
        prizes = pol.prizes(state, fcast)
        pr = np.array([prizes[p] for p in exo.point_ids])

        res = router.solve(backend, pr, np.ceil(fill), vehicles, dist_m, time_s, fixed_cost=trip_fixed, seed=seed * 1000 + d, **rkw)
        visited = np.array(sorted({i for r in res.routes for i in r}), dtype=int)
        coll_mat = fill_mat[visited].sum(0) if len(visited) else np.zeros(len(MATERIALS))
        collected = float(coll_mat.sum())
        fl = flow.day(coll_mat)
        stock_start = float(fill.sum())
        fill_mat[visited] = 0.0
        fill_mat = fill_mat + exo.mat[d]
        total_now = fill_mat.sum(1)
        over = np.maximum(total_now - exo.cap, 0.0)
        hit = over > 0
        fill_mat[hit] *= (exo.cap[hit] / total_now[hit])[:, None]
        fill_end[d] = fill_mat.sum(1)
        stock_end = float(fill_end[d].sum())
        gen_total = float(exo.gen[d].sum())

        trips = len(res.routes)
        vehs = {vid.split("_")[0] for vid in res.vehicle_ids}
        km = sum(res.distance_km) + 2.0 * leg_km * trips
        hours = (sum(res.time_s) + 2.0 * leg_s * trips) / 3600.0 + service_h * len(visited)
        rec = {f"rec_{m}_kg": fl.recovered_kg[m] for m in MATERIALS}
        rows.append({"policy": policy_name, "seed": seed, "day": d, "synthetic": True, "generated_kg": gen_total, "collected_kg": collected,
                     "overflow_events": int(hit.sum()), "overflow_kg": float(over.sum()), "km": km, "vehicle_hours": hours, "trips": trips,
                     "vehicles_used": len(vehs), "stops": len(visited), "routing_cost_inr": res.routing_cost_inr,
                     "fixed_daily_cost_inr": fixed_daily * len(vehs), **rec, "recovered_value_inr": fl.recovered_value_inr,
                     "landfill_kg": fl.landfill_kg, "spilled_kg": fl.spilled_kg, "over_capacity": int(fl.over_capacity),
                     "stock_start_kg": stock_start, "stock_end_kg": stock_end,
                     "ledger_residual_kg": stock_start + gen_total - stock_end - collected - float(over.sum()),
                     "flow_residual_kg": collected - sum(fl.recovered_kg.values()) - fl.landfill_kg, "router_status": res.status,
                     "router_runtime_s": res.runtime_s, "mean_risk": float(risk.mean())})
        if keep_detail:
            detail.append({"day": d, "point_ids": exo.point_ids, "fill_kg": fill.tolist(), "fill_end_kg": fill_end[d].tolist(), "capacity_kg": exo.cap.tolist(),
                           "overflow_risk": risk.tolist(), "recovery_value_inr": value.tolist(), "prize_inr": pr.tolist(), "gen_pred_kg": gen_pred.tolist(),
                           "visited": visited.tolist(), "routes": [{"vehicle": v, "points": r, "distance_km": dk, "load_kg": ld}
                                                                   for v, r, dk, ld in zip(res.vehicle_ids, res.routes, res.distance_km, res.load_kg)],
                           "dropped_with_prize": [int(i) for i in res.dropped if pr[i] > 0], "overflow": (over > 0).tolist(),
                           "flows": {"recovered_kg": fl.recovered_kg, "landfill_kg": fl.landfill_kg, "spilled_kg": fl.spilled_kg, "delivered_kg": fl.delivered_kg,
                                     "over_capacity": fl.over_capacity}})
    df = pd.DataFrame(rows)
    return RunResult(policy_name, seed, df, summarise(df, oc) | {"policy": policy_name, "seed": seed}, detail, time.time() - t_start)
